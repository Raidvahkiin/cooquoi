using Cooquoi.Context.Foodpedia;
using Cooquoi.Context.Household;
using Cooquoi.Platform;
using Cooquoi.Platform.Auditing;
using Cooquoi.Platform.Authentication;
using JasperFx;
using JasperFx.CodeGeneration;
using Raidvahkiin.Ddd;
using Raidvahkiin.Ddd.AspNetCore;
using Wolverine;
using Wolverine.EntityFrameworkCore;
using Wolverine.FluentValidation;
using Wolverine.Http;
using Wolverine.Http.FluentValidation;
using Wolverine.Persistence;
using Wolverine.Postgresql;

const string DatabaseConnection = "cooquoi";
const string WolverineSchema = "wolverine";

var builder = WebApplication.CreateBuilder(args);
builder.AddServiceDefaults();
builder.AddCooquoiAuthentication();
builder.AddCooquoiPlatform(DatabaseConnection);
builder.AddHouseholdContext(DatabaseConnection);
builder.AddFoodpediaContext(DatabaseConnection, WolverineSchema);

builder.Services.AddProblemDetails();
builder.Services.AddExceptionHandler<DomainExceptionHandler>();
if (builder.Environment.IsDevelopment())
{
    // Before Wolverine: its listeners may handle messages as soon as it starts.
    builder.Services.AddHostedService<DevelopmentDatabase>();
}

builder.Services.AddWolverineHttp();
builder.Host.UseWolverine(options =>
{
    options.Discovery.IncludeAssembly(HouseholdModule.Assembly);
    options.Discovery.IncludeAssembly(FoodpediaModule.Assembly);

    // Outbox: domain events are stored with the aggregate change, delivered after commit (ADR 0003).
    options.PersistMessagesWithPostgresql(builder.Configuration.RequiredConnectionString(DatabaseConnection), WolverineSchema);
    // Lightweight: one SaveChanges is the transaction (Household's sign-in opens its own around an advisory lock).
    options.UseEntityFrameworkCoreTransactions(TransactionMiddlewareMode.Lightweight);
    options.Policies.AutoApplyTransactions();
    options.Policies.UseDurableLocalQueues();
    options.Policies.Add<SystemActorPolicy>();
    options.PublishDomainEventsFromEntityFrameworkCore<IAggregateRoot, IDomainEvent>(aggregate => aggregate.DomainEvents);
    options.UseFluentValidation();

    // Development compiles handlers at runtime; elsewhere the code pre-generated by `codegen write`
    // (run before publishing) is used, with runtime compilation only as a fallback.
    options.CodeGeneration.TypeLoadMode = builder.Environment.IsDevelopment() ? TypeLoadMode.Dynamic : TypeLoadMode.Auto;
});

var app = builder.Build();
app.UseExceptionHandler();
app.UseAuthentication();
app.UseAuthorization();
app.UseCooquoiCommandPolicies();

app.MapDefaultEndpoints();
app.MapWolverineEndpoints(options => options.UseFluentValidationProblemDetailMiddleware());
return await app.RunJasperFxCommands(args);
